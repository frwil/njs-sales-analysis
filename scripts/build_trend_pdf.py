class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        self.setTitle("Analyse Soja/Concentrés — Tendance 4 semaines (octobre 2026)")
        self.setAuthor("William Francis Fohom, Data analyst")
        self.setSubject("P1 (05-10/10) vs W-1, W-2, W-3 — effet des baisses de prix soja")
