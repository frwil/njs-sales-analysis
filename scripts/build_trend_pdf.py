def fmt(x):
    if isinstance(x, (int, float)):
        return f"{x:,.1f}".replace(',', ' ').replace('.', ',')
    return str(x)

def fmt_signed(x):
    s = '+' if x >= 0 else ''
    return f"{s}{x:.1f}%".replace('.', ',')

def color_for_var(x):
    if x >= 10: return LIGHT_GREEN
    if x <= -10: return LIGHT_RED
    if x < 0: return LIGHT_YELLOW
    return LIGHT_GRAY

