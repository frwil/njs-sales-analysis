        self.setFont('DejaVuSans', 7)
        self.setFillColor(GRAY)
        self.drawString(1.5*cm, 0.9*cm, "William Francis Fohom, Data analyst")
        self.drawRightString(A4[0] - 1.5*cm, 0.9*cm, f"Page {self._pageNumber} / {page_count}")

